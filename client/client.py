import os
# Подключаем чтение режима из окружения запуска.
from rag.requests.controller import get
# Используем тот же контроллер, что и корневой main.py.
mode = os.getenv("RAG_MODE", "demo").strip().lower()
# Берем режим; без настройки будет помеченная демонстрация.
query = "Можно ли оплатить заказ после получения?"
# Задаем фиксированный вопрос об условиях оплаты.
print(get(query, top_k=2, mode=mode))
